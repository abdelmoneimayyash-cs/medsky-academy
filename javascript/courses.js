(function () {
  const dash = document.getElementById('mskyDash');
  if (!dash) return;

  const RING_CIRCUMFERENCE = 439.8;
  let hasAnimated = false;

  function easeOutCubic(t) {
    return 1 - Math.pow(1 - t, 3);
  }

  function animateCounter(el, target, duration) {
    const start = performance.now();
    function step(now) {
      const progress = Math.min((now - start) / duration, 1);
      const eased = easeOutCubic(progress);
      const value = Math.round(target * eased);
      el.textContent = value;
      if (progress < 1) {
        requestAnimationFrame(step);
      } else {
        el.textContent = target;
      }
    }
    requestAnimationFrame(step);
  }

  function animateRing(circleEl, targetPercent, duration) {
    const start = performance.now();
    function step(now) {
      const progress = Math.min((now - start) / duration, 1);
      const eased = easeOutCubic(progress);
      const currentPercent = targetPercent * eased;
      const offset = RING_CIRCUMFERENCE * (1 - currentPercent / 100);
      circleEl.style.strokeDashoffset = offset;
      if (progress < 1) {
        requestAnimationFrame(step);
      } else {
        circleEl.style.strokeDashoffset = RING_CIRCUMFERENCE * (1 - targetPercent / 100);
      }
    }
    requestAnimationFrame(step);
  }

  function animateProgressBar(el, targetPercent) {
    requestAnimationFrame(() => {
      el.style.width = targetPercent + '%';
    });
  }

  function runDashboardAnimations() {
    if (hasAnimated) return;
    hasAnimated = true;

    dash.classList.add('in-view');

    dash.querySelectorAll('[data-count-to]').forEach(el => {
      const target = parseInt(el.getAttribute('data-count-to'), 10) || 0;
      animateCounter(el, target, 1400);
    });

    const ringFill = document.getElementById('mskyRingFill');
    if (ringFill) {
      const target = parseFloat(ringFill.getAttribute('data-target')) || 0;
      ringFill.style.strokeDasharray = RING_CIRCUMFERENCE;
      ringFill.style.strokeDashoffset = RING_CIRCUMFERENCE;
      setTimeout(() => animateRing(ringFill, target, 1600), 120);
    }

    const progressFill = document.getElementById('mskyProgressFill');
    if (progressFill) {
      const target = parseFloat(progressFill.getAttribute('data-target')) || 0;
      setTimeout(() => animateProgressBar(progressFill, target), 200);
    }
  }

  if ('IntersectionObserver' in window) {
    const observer = new IntersectionObserver((entries) => {
      entries.forEach(entry => {
        if (entry.isIntersecting) {
          runDashboardAnimations();
          observer.unobserve(entry.target);
        }
      });
    }, { threshold: 0.25, rootMargin: '0px 0px -60px 0px' });

    observer.observe(dash);
  } else {
    runDashboardAnimations();
  }

  const continueBtn = dash.querySelector('.msky-btn-continue');
  if (continueBtn) {
    continueBtn.addEventListener('click', function (e) {
      const rect = continueBtn.getBoundingClientRect();
      const ripple = document.createElement('span');
      const size = Math.max(rect.width, rect.height);
      ripple.className = 'msky-ripple-el';
      ripple.style.width = ripple.style.height = size + 'px';
      ripple.style.left = (e.clientX - rect.left - size / 2) + 'px';
      ripple.style.top = (e.clientY - rect.top - size / 2) + 'px';
      continueBtn.appendChild(ripple);
      setTimeout(() => ripple.remove(), 650);

      const writtenTabBtn = document.querySelector('.tab-btn[data-tab="written"]');
      if (writtenTabBtn) {
        writtenTabBtn.click();
      }
    });
  }
})();

