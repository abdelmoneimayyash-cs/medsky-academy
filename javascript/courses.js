function t(key) {
  const dict = TRANSLATIONS[currentLang] || TRANSLATIONS.ar;
  return (key in dict) ? dict[key] : (TRANSLATIONS.ar[key] || key);
}

function applyLanguage(lang) {
  if (!TRANSLATIONS[lang]) lang = 'ar';
  currentLang = lang;
  localStorage.setItem(LANG_STORAGE_KEY, lang);

  const html = document.documentElement;
  html.setAttribute('lang', lang);
  html.setAttribute('dir', lang === 'ar' ? 'rtl' : 'ltr');

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    el.textContent = t(key);
  });
  document.querySelectorAll('[data-i18n-aria]').forEach(el => {
    el.setAttribute('aria-label', t(el.getAttribute('data-i18n-aria')));
  });
  document.querySelectorAll('[data-i18n-alt]').forEach(el => {
    el.setAttribute('alt', t(el.getAttribute('data-i18n-alt')));
  });
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    el.textContent = t(el.getAttribute('data-i18n-title'));
  });

  document.querySelectorAll('[data-lang]').forEach(b => {
    b.classList.toggle('active', b.dataset.lang === lang);
  });

  const activeTheme = document.documentElement.getAttribute('data-theme') || 'light';
  const themeValueEl = document.getElementById('mobileThemeValue');
  if (themeValueEl) themeValueEl.textContent = activeTheme === 'dark' ? t('theme_dark') : t('theme_light');

  if (currentModalKey) renderFooterModal(currentModalKey);

  if (typeof renderCertModal === 'function' && currentCertData) renderCertModal();
}

