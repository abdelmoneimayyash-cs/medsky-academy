(function () {
  const overlay = document.getElementById('certModalOverlay');
  const img = document.getElementById('certModalImg');
  const closeBtn = document.getElementById('certModalClose');
  const zoomWrap = document.getElementById('certZoomWrap');
  const zoomInBtn = document.getElementById('certZoomIn');
  const zoomOutBtn = document.getElementById('certZoomOut');
  const zoomResetBtn = document.getElementById('certZoomReset');

  if (!overlay || !img) return;

  if (closeBtn) closeBtn.addEventListener('click', closeCertificate);

  overlay.addEventListener('click', function (e) {
    if (e.target === overlay) closeCertificate();
  });

  document.addEventListener('keydown', function (e) {
    if (e.key === 'Escape' && overlay.classList.contains('open')) closeCertificate();
  });

  if (zoomInBtn) zoomInBtn.addEventListener('click', function () {
    _certScale = Math.min(_certScale + 0.4, 3);
    _certApplyTransform();
  });
  if (zoomOutBtn) zoomOutBtn.addEventListener('click', function () {
    _certScale = Math.max(_certScale - 0.4, 1);
    if (_certScale === 1) { _certPosX = 0; _certPosY = 0; }
    _certApplyTransform();
  });
  if (zoomResetBtn) zoomResetBtn.addEventListener('click', _certResetZoom);

  if (zoomWrap) {
    zoomWrap.addEventListener('wheel', function (e) {
      e.preventDefault();
      const delta = e.deltaY > 0 ? -0.2 : 0.2;
      _certScale = Math.min(Math.max(_certScale + delta, 1), 3);
      if (_certScale === 1) { _certPosX = 0; _certPosY = 0; }
      _certApplyTransform();
    }, { passive: false });

    zoomWrap.addEventListener('pointerdown', function (e) {
      if (_certScale <= 1) return;
      _certDragging = true;
      zoomWrap.classList.add('is-dragging');
      _certStartX = e.clientX - _certPosX;
      _certStartY = e.clientY - _certPosY;
      zoomWrap.setPointerCapture(e.pointerId);
    });
    zoomWrap.addEventListener('pointermove', function (e) {
      if (!_certDragging) return;
      _certPosX = e.clientX - _certStartX;
      _certPosY = e.clientY - _certStartY;
      _certApplyTransform();
    });
    zoomWrap.addEventListener('pointerup', function (e) {
      _certDragging = false;
      zoomWrap.classList.remove('is-dragging');
      if (zoomWrap.hasPointerCapture && zoomWrap.hasPointerCapture(e.pointerId)) {
        zoomWrap.releasePointerCapture(e.pointerId);
      }
    });
    zoomWrap.addEventListener('pointerleave', function () {
      _certDragging = false;
      zoomWrap.classList.remove('is-dragging');
    });

    zoomWrap.addEventListener('dblclick', function () {
      if (_certScale > 1) { _certResetZoom(); }
      else { _certScale = 2; _certApplyTransform(); }
    });
  }
})();