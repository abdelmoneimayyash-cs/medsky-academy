  /* ---------- طبقة الاتصال بالـ API ---------- */
  async function api(path, body) {
    let res;
    try {
      res = await fetch("/api" + path, {
        method: "POST",
        credentials: "same-origin",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify(body || {}),
      });
    } catch {
      return { ok: false, status: 0, data: { error: "network" } };
    }
    let data = {};
    try { data = await res.json(); } catch { /* ignore */ }
    return { ok: res.ok, status: res.status, data };
  }

  // يعرض خطأ السيرفر على الحقول أو على النموذج. يرجع true إذا تم التعامل معه.
  function showServerError(form, fieldMap, r) {
    const d = r.data || {};
    if (d.error === "validation" && d.fields) {
      let any = false;
      for (const [name, code] of Object.entries(d.fields)) {
        const id = fieldMap[name];
        if (id) { setFieldError(id, SERVER_ERR[code] || "errors.server"); any = true; }
      }
      if (any) return;
    }
    const keyByErr = {
      invalid_credentials: "errors.invalidCredentials",
      too_many_requests: "errors.tooMany",
      network: "errors.network",
      invalid_token: "errors.invalidToken",
      google_failed: "login.googleError",
    };
    setFormMessage(form, keyByErr[d.error] || "errors.server", false);
  }

